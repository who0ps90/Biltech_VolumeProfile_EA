"""Regenerate hand-check CSV and MQL5 input/expected fixtures from JSON."""
import csv
import json
from pathlib import Path

here = Path(__file__).parent
fixture = json.loads((here / "signal_cases.json").read_text(encoding="utf-8"))
defaults = fixture["defaults"]
lines = ["// Generated by generate_native_fixtures.py from synthetic signal_cases.json.",
         "// Expectations are fixture data; production Signals.mqh calculates results.",
         "void TestSignalFixtures()", "{"]
csv_rows = []
for case in fixture["cases"]:
    expected = {x["index"]: x for x in case["expected"]}
    prior = case.get("previous_bar_close", defaults["previous_bar_close"])
    session_close = case.get("previous_session_close", defaults["previous_session_close"])
    lines += [" {", f'  string label="{case["name"]}";', "  CBVPSignals engine;",
              f'  engine.Init(FixtureConfig("{case["enabled"]}"),0.1,300);',
              f"  BVPProfile p=FixtureProfile({session_close});",
              f"  MqlRates prev=FixtureRate({prior},{prior},{prior},{prior},FIXTURE_T0-300),bar;",
              "  BVPSignal got,duplicate;"]
    for i, values in enumerate(case["bars"]):
        op, hi, lo, cl, atr = values
        if not (lo <= min(op, cl) <= max(op, cl) <= hi):
            raise ValueError(f"{case['name']} index {i}: invalid OHLC")
        e = expected.get(i, {})
        lines += [f"  bar=FixtureRate({op},{hi},{lo},{cl},FIXTURE_T0+{i}*300);",
                  f"  engine.OnBar(bar,prev,{atr},p,got);",
                  f'  CheckSignal(got,label+":bar{i}",{e.get("setup",0)},{e.get("direction",0)},{e.get("stop",0)},{e.get("atr",0)},{e.get("buffer",0)},bar.time,p.start_utc);',
                  f"  engine.OnBar(bar,prev,{atr},p,duplicate);",
                  f'  Check(!duplicate.valid,label+":bar{i}:duplicate ignored");',
                  "  prev=bar;"]
        csv_rows.append([case["name"], case["enabled"], session_close, prior, i, i*300,
                         op, hi, lo, cl, atr, e.get("setup", ""), e.get("direction", ""), e.get("stop", "")])
        prior = cl
    lines += [" }"]
lines += ["}", ""]
(here / "generated_signal_fixtures.mqh").write_text("\n".join(lines), encoding="utf-8")
with (here / "signal_handcheck.csv").open("w", newline="", encoding="utf-8") as f:
    writer = csv.writer(f)
    writer.writerow(["synthetic_case", "enabled", "reference_close", "preceding_close", "index", "seconds_from_T0",
                     "open", "high", "low", "close", "completed_ATR", "expected_setup", "expected_direction", "expected_stop"])
    writer.writerows(csv_rows)
print(f"Generated {len(fixture['cases'])} cases / {len(csv_rows)} completed bars.")
